local mainMod = "SUPER"

hl.bind(mainMod .. " + Return",          hl.dsp.exec_cmd(terminal))
hl.bind(mainMod .. " + semicolon",       hl.dsp.exec_cmd(menu))
hl.bind(mainMod .. " + SHIFT + B",       hl.dsp.window.close())
hl.bind(mainMod .. " + SHIFT + N",       hl.dsp.exit())
hl.bind(mainMod .. " + M",               hl.dsp.window.float({ action = "toggle" }))
hl.bind(mainMod .. " + F",               hl.dsp.window.fullscreen())

-- Graphite layout: h, l, k, and j correspond to left, right, up, and down.
local directions = {
    h = "l",
    l = "r",
    k = "u",
    j = "d",
}

for key, direction in pairs(directions) do
    hl.bind(mainMod .. " + " .. key,         hl.dsp.focus({ direction = direction }))
    hl.bind(mainMod .. " + SHIFT + " .. key, hl.dsp.window.move({ direction = direction }))
end

hl.bind(mainMod .. " + CTRL + H", hl.dsp.workspace.move({ monitor = "DP-3" }))
hl.bind(mainMod .. " + CTRL + L", hl.dsp.workspace.move({ monitor = "DP-1" }))
hl.bind(mainMod .. " + Tab",      hl.dsp.window.cycle_next())
hl.bind(mainMod .. " + SHIFT + Tab", hl.dsp.window.cycle_next({ next = false }))

-- Switch workspaces with mainMod + [0-9]
-- Move active window to a workspace with mainMod + SHIFT + [0-9]
for i = 1, 10 do
    local key = i % 10 -- 10 maps to key 0
    hl.bind(mainMod .. " + " .. key,             hl.dsp.focus({ workspace = i}))
    hl.bind(mainMod .. " + SHIFT + " .. key,     hl.dsp.window.move({ workspace = i }))
end

-- Scroll through existing workspaces with mainMod + scroll
hl.bind(mainMod .. " + mouse_down", hl.dsp.focus({ workspace = "e+1" }))
hl.bind(mainMod .. " + mouse_up",   hl.dsp.focus({ workspace = "e-1" }))

-- Move/resize windows with mainMod + LMB/RMB and dragging
hl.bind(mainMod .. " + mouse:272", hl.dsp.window.drag(),   { mouse = true })
hl.bind(mainMod .. " + mouse:273", hl.dsp.window.resize(), { mouse = true })


